create extension if not exists pgcrypto;

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  organiser_id uuid references auth.users(id) on delete set null,
  title text not null check (char_length(trim(title)) between 4 and 100),
  category text not null check (category in ('Music', 'Food & drink', 'Arts & culture', 'Wellness')),
  starts_at timestamptz not null,
  location text not null check (char_length(trim(location)) between 3 and 120),
  city text not null check (city in ('Mumbai', 'Bengaluru', 'New Delhi', 'Hyderabad')),
  price integer not null check (price between 0 and 100000),
  capacity integer not null check (capacity between 1 and 100000),
  host text not null check (char_length(trim(host)) between 2 and 80),
  tag text not null default 'New listing' check (char_length(trim(tag)) between 1 and 40),
  description text not null check (char_length(trim(description)) between 20 and 2000),
  image text not null check (image like 'https://images.unsplash.com/%'),
  published boolean not null default true,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.saved_events (
  user_id uuid not null references auth.users(id) on delete cascade,
  event_id bigint not null references public.events(id) on delete cascade,
  created_at timestamptz not null default timezone('utc', now()),
  primary key (user_id, event_id)
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  event_id bigint not null references public.events(id) on delete restrict,
  user_id uuid not null references auth.users(id) on delete restrict,
  name text not null check (char_length(trim(name)) between 2 and 80),
  email text not null check (char_length(trim(email)) between 3 and 254),
  quantity integer not null check (quantity between 1 and 8),
  total integer not null check (total >= 0),
  created_at timestamptz not null default timezone('utc', now()),
  checked_in_at timestamptz
);

create index if not exists events_city_starts_at_idx on public.events (city, starts_at);
create index if not exists events_organiser_id_idx on public.events (organiser_id);
create index if not exists bookings_event_id_idx on public.bookings (event_id);
create index if not exists bookings_user_id_idx on public.bookings (user_id);

alter table public.events enable row level security;
alter table public.saved_events enable row level security;
alter table public.bookings enable row level security;

drop policy if exists "Published events are public" on public.events;
create policy "Published events are public"
  on public.events for select
  using (published = true or organiser_id = auth.uid());

drop policy if exists "Organisers create their own events" on public.events;
create policy "Organisers create their own events"
  on public.events for insert to authenticated
  with check (organiser_id = auth.uid());

drop policy if exists "Organisers update their own events" on public.events;
create policy "Organisers update their own events"
  on public.events for update to authenticated
  using (organiser_id = auth.uid())
  with check (organiser_id = auth.uid());

drop policy if exists "Organisers delete their own events" on public.events;
create policy "Organisers delete their own events"
  on public.events for delete to authenticated
  using (organiser_id = auth.uid());

drop policy if exists "Users read their saved events" on public.saved_events;
create policy "Users read their saved events"
  on public.saved_events for select to authenticated
  using (user_id = auth.uid());

drop policy if exists "Users save events for themselves" on public.saved_events;
create policy "Users save events for themselves"
  on public.saved_events for insert to authenticated
  with check (user_id = auth.uid());

drop policy if exists "Users remove their saved events" on public.saved_events;
create policy "Users remove their saved events"
  on public.saved_events for delete to authenticated
  using (user_id = auth.uid());

drop policy if exists "Users and organisers read relevant bookings" on public.bookings;
create policy "Users and organisers read relevant bookings"
  on public.bookings for select to authenticated
  using (
    user_id = auth.uid()
    or exists (
      select 1 from public.events e
      where e.id = bookings.event_id and e.organiser_id = auth.uid()
    )
  );

create or replace function public.get_event_availability(p_event_id bigint)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select greatest(
    0,
    e.capacity - coalesce((select sum(b.quantity) from public.bookings b where b.event_id = e.id), 0)::integer
  )::integer
  from public.events e
  where e.id = p_event_id and e.published = true;
$$;

create or replace function public.book_event(
  p_event_id bigint,
  p_quantity integer,
  p_name text,
  p_email text
)
returns public.bookings
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_event public.events%rowtype;
  v_sold integer;
  v_booking public.bookings%rowtype;
begin
  if v_user_id is null then
    raise exception 'You must be signed in to book an event.' using errcode = '42501';
  end if;
  if p_quantity is null or p_quantity < 1 or p_quantity > 8 then
    raise exception 'Choose between 1 and 8 tickets.' using errcode = '22023';
  end if;
  if p_name is null or char_length(trim(p_name)) not between 2 and 80 then
    raise exception 'Please enter a valid name.' using errcode = '22023';
  end if;
  if p_email is null or char_length(trim(p_email)) not between 3 and 254 or position('@' in p_email) < 2 then
    raise exception 'Please enter a valid email address.' using errcode = '22023';
  end if;

  select * into v_event
  from public.events
  where id = p_event_id and published = true and starts_at > now()
  for update;

  if not found then
    raise exception 'This event is no longer available.' using errcode = 'P0002';
  end if;

  select coalesce(sum(quantity), 0)::integer into v_sold
  from public.bookings
  where event_id = v_event.id;

  if v_sold + p_quantity > v_event.capacity then
    raise exception 'There are not enough tickets left.' using errcode = 'P0001';
  end if;

  insert into public.bookings (event_id, user_id, name, email, quantity, total)
  values (v_event.id, v_user_id, trim(p_name), lower(trim(p_email)), p_quantity, v_event.price * p_quantity)
  returning * into v_booking;

  return v_booking;
end;
$$;

create or replace function public.check_in_booking(p_booking_id uuid)
returns public.bookings
language plpgsql
security definer
set search_path = public
as $$
declare
  v_booking public.bookings%rowtype;
begin
  if auth.uid() is null then
    raise exception 'You must be signed in to check in attendees.' using errcode = '42501';
  end if;

  select b.* into v_booking
  from public.bookings b
  join public.events e on e.id = b.event_id
  where b.id = p_booking_id and e.organiser_id = auth.uid()
  for update;

  if not found then
    raise exception 'This booking is not managed by your account.' using errcode = '42501';
  end if;

  if v_booking.checked_in_at is null then
    update public.bookings
    set checked_in_at = timezone('utc', now())
    where id = v_booking.id
    returning * into v_booking;
  end if;

  return v_booking;
end;
$$;

